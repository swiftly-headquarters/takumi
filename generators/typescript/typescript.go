// Package typescript generates a dependency-free, fetch-based TypeScript SDK.
package typescript

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"regexp"
	"slices"
	"strings"
	"unicode"

	"github.com/swiftly-headquarters/takumi/spec"
)

//go:embed runtime.ts
var runtime string

const header = "// Code generated by takumi. DO NOT EDIT.\n\n"

var identRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

type gen struct {
	doc    *spec.Document
	names  map[string]string // schema component name -> TS type name
	prefix string            // "" inside types.ts, "T." inside client.ts
}

// Generate returns the SDK files keyed by relative path.
func Generate(doc *spec.Document) (map[string][]byte, error) {
	g := &gen{doc: doc, names: map[string]string{}}
	used := map[string]bool{}
	for _, name := range spec.SortedKeys(doc.Components.Schemas) {
		g.names[name] = unique(pascal(name), used)
	}
	return map[string][]byte{
		"types.ts":  []byte(g.types()),
		"client.ts": []byte(g.client()),
		"index.ts":  []byte(header + "export * from \"./client.js\";\nexport * from \"./types.js\";\n"),
	}, nil
}

func (g *gen) types() string {
	var b strings.Builder
	b.WriteString(header)
	if len(g.names) == 0 {
		b.WriteString("export {};\n")
	}
	for _, name := range spec.SortedKeys(g.doc.Components.Schemas) {
		s := g.doc.Components.Schemas[name]
		b.WriteString(doc(s.Description, s.Deprecated, ""))
		if isPlainObject(s) {
			fmt.Fprintf(&b, "export interface %s %s\n\n", g.names[name], g.object(s, "  "))
		} else {
			fmt.Fprintf(&b, "export type %s = %s;\n\n", g.names[name], g.typ(s))
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

func isPlainObject(s *spec.Schema) bool {
	return s.Ref == "" && len(s.Properties) > 0 && len(s.AllOf)+len(s.OneOf)+len(s.AnyOf)+len(s.Enum) == 0 &&
		!s.Nullable && (len(s.Type) == 0 || slices.Equal(s.Type, spec.Types{"object"}))
}

func (g *gen) typ(s *spec.Schema) string {
	if s == nil {
		return "unknown"
	}
	if s.False {
		return "never"
	}
	if s.Ref != "" {
		if name, ok := g.names[spec.SchemaName(s.Ref)]; ok {
			return g.prefix + name
		}
		return "unknown"
	}

	var t string
	switch {
	case len(s.Enum) > 0:
		t = literals(s.Enum)
	case s.Const != nil:
		t = literals([]any{s.Const})
	case len(s.OneOf) > 0:
		t = g.join(s.OneOf, " | ")
	case len(s.AnyOf) > 0:
		t = g.join(s.AnyOf, " | ")
	default:
		types := s.Type
		if len(types) == 0 {
			switch {
			case s.Properties != nil || s.AdditionalProperties != nil:
				types = spec.Types{"object"}
			case s.Items != nil:
				types = spec.Types{"array"}
			}
		}
		var parts []string
		for _, typ := range types {
			parts = append(parts, g.basic(typ, s))
		}
		t = strings.Join(parts, " | ")
	}

	if len(s.AllOf) > 0 {
		parts := []string{g.join(s.AllOf, " & ")}
		if t != "" {
			parts = append(parts, paren(t))
		}
		t = strings.Join(parts, " & ")
	}
	if t == "" {
		t = "unknown"
	}
	if s.Nullable && t != "unknown" {
		t += " | null"
	}
	return t
}

func (g *gen) basic(typ string, s *spec.Schema) string {
	switch typ {
	case "string":
		if s.Format == "binary" {
			return "Blob"
		}
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "array":
		item := g.typ(s.Items)
		if identRe.MatchString(strings.ReplaceAll(item, ".", "")) {
			return item + "[]"
		}
		return "Array<" + item + ">"
	case "object":
		if len(s.Properties) == 0 {
			if s.AdditionalProperties != nil && s.AdditionalProperties.False {
				return "Record<string, never>"
			}
			return "Record<string, " + g.typ(s.AdditionalProperties) + ">"
		}
		return g.object(s, "")
	}
	return "unknown"
}

// object renders `{ ... }`. A non-empty indent renders one documented property per line.
func (g *gen) object(s *spec.Schema, indent string) string {
	var props []string
	for _, name := range spec.SortedKeys(s.Properties) {
		p := s.Properties[name]
		opt := "?"
		if slices.Contains(s.Required, name) {
			opt = ""
		}
		prop := fmt.Sprintf("%s%s: %s;", key(name), opt, g.typ(p))
		if indent != "" {
			prop = doc(p.Description, p.Deprecated, indent) + indent + prop
		}
		props = append(props, prop)
	}
	if ap := s.AdditionalProperties; ap != nil && !ap.False {
		// unknown: an index signature must accept every declared property type.
		props = append(props, indent+"[key: string]: unknown;")
	}
	if indent == "" {
		return "{ " + strings.Join(props, " ") + " }"
	}
	return "{\n" + strings.Join(props, "\n") + "\n}"
}

func (g *gen) join(schemas []*spec.Schema, sep string) string {
	parts := make([]string, len(schemas))
	for i, s := range schemas {
		parts[i] = paren(g.typ(s))
	}
	return strings.Join(parts, sep)
}

func (g *gen) client() string {
	g.prefix = "T."
	defer func() { g.prefix = "" }()

	baseURL := ""
	if len(g.doc.Servers) > 0 {
		baseURL = g.doc.Servers[0].URL
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("import type * as T from \"./types.js\";\n\n")
	b.WriteString(strings.Replace(runtime, "__BASE_URL__", strings.Trim(jsonString(baseURL), `"`), 1))
	root := g.resourceTree()
	g.assign(root, "", map[string]bool{"Client": true, "BaseClient": true, "ApiError": true})
	props, names := members(root, "options", "request", "send", "constructor")
	children := spec.SortedKeys(root.children)
	for _, name := range children {
		g.writeClass(&b, root.children[name])
	}
	b.WriteString("\nexport class Client extends BaseClient {\n")
	for _, name := range children {
		fmt.Fprintf(&b, "  readonly %s = new %s(this.send);\n", props[name], root.children[name].class)
	}
	for i, r := range root.routes {
		if i > 0 || len(children) > 0 {
			b.WriteString("\n")
		}
		g.method(&b, r.Op, names[i], "this.request")
	}
	b.WriteString("}\n")
	return b.String()
}

// resourceTree groups the planned routes by resource chain: user.pets lives at root.children["user"].children["pets"].
func (g *gen) resourceTree() *node {
	root := &node{children: map[string]*node{}}
	for _, r := range g.doc.Plan() {
		n := root
		for _, name := range r.Resource {
			if n.children[name] == nil {
				n.children[name] = &node{children: map[string]*node{}}
			}
			n = n.children[name]
		}
		n.routes = append(n.routes, r)
	}
	return root
}

type node struct {
	class    string
	children map[string]*node
	routes   []spec.Route
}

// assign gives every descendant of n a unique class name (user.pets -> UserPetsApi).
func (g *gen) assign(n *node, prefix string, classes map[string]bool) {
	for _, name := range spec.SortedKeys(n.children) {
		c := n.children[name]
		c.class = unique(prefix+pascal(name)+"Api", classes)
		g.assign(c, prefix+pascal(name), classes)
	}
}

// members picks the property name of each child and the method name of each
// route, avoiding the reserved names and each other.
func members(n *node, reserved ...string) (props map[string]string, names []string) {
	used := map[string]bool{}
	for _, r := range reserved {
		used[r] = true
	}
	props = map[string]string{}
	for _, name := range spec.SortedKeys(n.children) {
		props[name] = unique(ident(name), used)
	}
	for _, r := range n.routes {
		names = append(names, unique(ident(r.Method), used))
	}
	return props, names
}

func ident(name string) string {
	if name == "" || unicode.IsDigit(rune(name[0])) {
		return "_" + name
	}
	return name
}

func (g *gen) writeClass(b *strings.Builder, n *node) {
	children := spec.SortedKeys(n.children)
	for _, name := range children {
		g.writeClass(b, n.children[name])
	}
	props, names := members(n, "send", "constructor")
	fmt.Fprintf(b, "\nexport class %s {\n", n.class)
	for _, name := range children {
		fmt.Fprintf(b, "  readonly %s: %s;\n", props[name], n.children[name].class)
	}
	send := "send: Send"
	if len(n.routes) > 0 {
		send = "private readonly " + send
	}
	if len(children) == 0 {
		fmt.Fprintf(b, "  constructor(%s) {}\n", send)
	} else {
		fmt.Fprintf(b, "  constructor(%s) {\n", send)
		for _, name := range children {
			fmt.Fprintf(b, "    this.%s = new %s(send);\n", props[name], n.children[name].class)
		}
		b.WriteString("  }\n")
	}
	for i, r := range n.routes {
		b.WriteString("\n")
		g.method(b, r.Op, names[i], "this.send")
	}
	b.WriteString("}\n")
}

func (g *gen) method(b *strings.Builder, op spec.Op, name, send string) {
	fields, required := g.paramFields(op)
	bodyKind, contentType := "", ""
	if rb := op.RequestBody; rb != nil {
		var field string
		field, bodyKind, contentType = g.bodyField(rb)
		fields = append(fields, field)
		required = required || rb.Required
	}
	resType, parse := g.response(op)

	b.WriteString(doc(strings.TrimSpace(op.Summary+"\n\n"+op.Description), op.Deprecated, "  "))
	args, call := "init?: RequestInit", "{}"
	if len(fields) > 0 {
		params := "params: { " + strings.Join(fields, "; ") + " }"
		if !required {
			params += " = {}"
		}
		args, call = params+", "+args, "params"
	}
	fmt.Fprintf(b, "  %s(%s): Promise<%s> {\n", name, args, resType)
	fmt.Fprintf(b, "    return %s(%s, %s, %s, %s, %s, %s, %s);\n",
		send, jsonString(strings.ToUpper(op.Method)), jsonString(op.Path), call,
		jsonString(bodyKind), jsonString(contentType), jsonString(parse), styleArgs(op))
	b.WriteString("  }\n")
}

var paramFieldNames = []struct{ in, field string }{
	{"path", "path"}, {"query", "query"}, {"header", "headers"}, {"cookie", "cookies"},
}

// paramFields renders one `path: {...}` / `query?: {...}` entry per parameter
// location in use, and reports whether any of them has a required member.
func (g *gen) paramFields(op spec.Op) (fields []string, required bool) {
	for _, loc := range paramFieldNames {
		var props []string
		groupRequired := false
		for _, p := range op.Params {
			if p.In != loc.in {
				continue
			}
			opt := "?"
			if p.Required || loc.in == "path" {
				opt, groupRequired = "", true
			}
			props = append(props, fmt.Sprintf("%s%s: %s;", key(p.Name), opt, g.typ(p.Schema)))
		}
		if len(props) == 0 {
			continue
		}
		opt := "?"
		if groupRequired {
			opt, required = "", true
		}
		fields = append(fields, fmt.Sprintf("%s%s: { %s }", loc.field, opt, strings.Join(props, " ")))
	}
	return fields, required
}

// bodyField renders the `body` entry and returns the runtime body kind and content type.
func (g *gen) bodyField(rb *spec.RequestBody) (field, kind, contentType string) {
	contentType, mt := pick(rb.Content)
	kind = kindOf(contentType)
	bodyType := g.typ(mt.Schema)
	switch {
	case kind == "raw" && strings.HasPrefix(contentType, "text/"):
		bodyType = "string"
	case kind == "raw":
		bodyType = "BodyInit"
	}
	opt := "?"
	if rb.Required {
		opt = ""
	}
	return fmt.Sprintf("body%s: %s", opt, bodyType), kind, contentType
}

// styleArgs renders the trailing runtime arguments: `init`, plus a map of
// non-default parameter styles keyed "<in>.<name>" when there are any.
func styleArgs(op spec.Op) string {
	styles := map[string]string{}
	for _, p := range op.Params {
		if st := p.SerStyle(); st != "" {
			styles[p.In+"."+p.Name] = st
		}
	}
	if len(styles) == 0 {
		return "init"
	}
	return "init, " + jsonString(styles)
}

// response picks the first 2xx response and returns its TS type and how to parse it.
func (g *gen) response(op spec.Op) (string, string) {
	codes := spec.SortedKeys(op.Responses) // "200" < "201" < "2XX" < "default"
	for _, code := range codes {
		if !strings.HasPrefix(code, "2") {
			continue
		}
		ct, mt := pick(op.Responses[code].Content)
		switch {
		case mt == nil || code == "204":
			return "void", "void"
		case kindOf(ct) == "json":
			return g.typ(mt.Schema), "json"
		case strings.HasPrefix(ct, "text/"):
			return "string", "text"
		default:
			return "Blob", "blob"
		}
	}
	return "unknown", "json"
}

// pick chooses the preferred media type: JSON first, then forms, then whatever is first.
func pick(content map[string]*spec.MediaType) (string, *spec.MediaType) {
	keys := spec.SortedKeys(content)
	if len(keys) == 0 {
		return "", nil
	}
	for _, want := range []string{"json", "multipart", "form"} {
		for _, k := range keys {
			if kindOf(k) == want {
				return k, content[k]
			}
		}
	}
	return keys[0], content[keys[0]]
}

func kindOf(contentType string) string {
	ct, _, _ := strings.Cut(contentType, ";")
	switch {
	case ct == "application/json" || strings.HasSuffix(ct, "+json"):
		return "json"
	case ct == "multipart/form-data":
		return "multipart"
	case ct == "application/x-www-form-urlencoded":
		return "form"
	}
	return "raw"
}

func doc(text string, deprecated bool, indent string) string {
	var lines []string
	if text = strings.TrimSpace(text); text != "" {
		lines = strings.Split(strings.ReplaceAll(text, "*/", "*\\/"), "\n")
	}
	if deprecated {
		lines = append(lines, "@deprecated")
	}
	if len(lines) == 0 {
		return ""
	}
	if len(lines) == 1 {
		return indent + "/** " + lines[0] + " */\n"
	}
	var b strings.Builder
	b.WriteString(indent)
	b.WriteString("/**\n")
	for _, l := range lines {
		b.WriteString(strings.TrimRight(indent+" * "+l, " "))
		b.WriteString("\n")
	}
	b.WriteString(indent)
	b.WriteString(" */\n")
	return b.String()
}

func literals(values []any) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = jsonString(v)
	}
	return strings.Join(parts, " | ")
}

func paren(t string) string {
	if strings.ContainsAny(t, "|&") {
		return "(" + t + ")"
	}
	return t
}

func key(name string) string {
	if identRe.MatchString(name) {
		return name
	}
	return jsonString(name)
}

func jsonString(v any) string {
	out, _ := json.Marshal(v)
	return string(out)
}

func words(s string) []string {
	return strings.FieldsFunc(s, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
}

func pascal(s string) string {
	var b strings.Builder
	for _, w := range words(s) {
		r := []rune(w)
		b.WriteString(strings.ToUpper(string(r[0])))
		b.WriteString(string(r[1:]))
	}
	out := b.String()
	if out == "" || unicode.IsDigit(rune(out[0])) {
		out = "_" + out
	}
	return out
}

func unique(name string, used map[string]bool) string {
	out := name
	for i := 2; used[out]; i++ {
		out = fmt.Sprintf("%s%d", name, i)
	}
	used[out] = true
	return out
}
