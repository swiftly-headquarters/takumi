//go:embed runtime.go.txt
var runtime string

const header = "// Code generated by takumi. DO NOT EDIT.\n\n"

// reserved are the exported names runtime.go.txt declares.
var reserved = []string{"APIError", "Client", "ClientOption", "NewClient", "RequestOption",
	"WithBaseURL", "WithHTTPClient", "WithHeader", "WithHeaders", "WithRequestHeader"}

var initialisms = map[string]string{"api": "API", "html": "HTML", "http": "HTTP", "id": "ID", "ip": "IP",
	"json": "JSON", "sql": "SQL", "uri": "URI", "url": "URL", "uuid": "UUID", "xml": "XML"}

type gen struct {
	doc   *spec.Document
	used  map[string]bool
	names map[string]string
	decls []string
	io    bool
}

type field struct {
	name, typ, doc, tag string
}

type node struct {
	class    string
	prefix   string
	children map[string]*node
	routes   []spec.Route
}

func Generate(doc *spec.Document) (map[string][]byte, error) {
	g := &gen{doc: doc, used: map[string]bool{}, names: map[string]string{}}
	for _, name := range reserved {
		g.used[name] = true
	}
	for _, name := range spec.SortedKeys(doc.Components.Schemas) {
		g.names[name] = g.reserve(exported(name))
	}
	routes := doc.Plan()
	root := &node{class: "Client", children: map[string]*node{}}
	for _, r := range routes {
		n := root
		for _, name := range r.Resource {
			if n.children[name] == nil {
				n.children[name] = &node{prefix: n.prefix + exported(name), children: map[string]*node{}}
			}
			n = n.children[name]
		}
		n.routes = append(n.routes, r)
	}
	g.assign(root)

	for _, name := range spec.SortedKeys(doc.Components.Schemas) {
		g.component(name, doc.Components.Schemas[name])
	}

	var client strings.Builder
	baseURL := ""
	if len(doc.Servers) > 0 {
		baseURL = doc.Servers[0].URL
	}
	fmt.Fprintf(&client, "const defaultBaseURL = %s\n\n", strconv.Quote(baseURL))
	client.WriteString("// NewClient returns a Client for the first server of the spec. Override it with WithBaseURL.\n")
	client.WriteString("func NewClient(opts ...ClientOption) *Client {\n\tb := newBase(defaultBaseURL, opts)\n\treturn newClient(&b)\n}\n\n")
	g.services(&client, root)

	var types strings.Builder
	for _, d := range g.decls {
		types.WriteString(d)
	}
	var imports []string
	if g.io {
		imports = append(imports, "io")
	}
	files := map[string]string{
		"types.go":   file(imports, types.String()),
		"client.go":  file(opt(len(routes) > 0, "context"), client.String()),
		"runtime.go": header + runtime,
	}
	out := map[string][]byte{}
	for name, src := range files {
		formatted, err := format.Source([]byte(src))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		out[name] = formatted
	}
	return out, nil
}

func opt(ok bool, imp string) []string {
	if ok {
		return []string{imp}
	}
	return nil
}

func file(imports []string, body string) string {
	var b strings.Builder
	b.WriteString(header + "package sdk\n\n")
	if len(imports) > 0 {
		b.WriteString("import (\n")
		for _, imp := range imports {
			b.WriteString("\t")
			b.WriteString(strconv.Quote(imp))
			b.WriteString("\n")
		}
		b.WriteString(")\n\n")
	}
	b.WriteString(body)
	return b.String()
}

func (g *gen) reserve(name string) string { return unique(name, g.used) }

func (g *gen) assign(n *node) {
	for _, name := range spec.SortedKeys(n.children) {
		c := n.children[name]
		c.class = g.reserve(c.prefix + "Service")
		g.assign(c)
	}
}

func (g *gen) component(name string, s *spec.Schema) {
	goName := g.names[name]
	if s.Ref == "" && len(g.collect(s).props) > 0 {
		g.structType(goName, s)
		return
	}
	t := g.typ(s, goName)
	g.decls = append(g.decls, goDoc(s.Description, s.Deprecated)+fmt.Sprintf("type %s %s\n\n", goName, t))
}

func (g *gen) typ(s *spec.Schema, hint string) string {
	switch {
	case s == nil || s.False:
		return "any"
	case s.Ref != "":
		if n, ok := g.names[spec.SchemaName(s.Ref)]; ok {
			return n
		}
		return "any"
	case len(s.OneOf)+len(s.AnyOf) > 0:
		return "any"
	case len(s.AllOf) == 1 && len(s.Properties) == 0 && len(s.Type) == 0:
		return g.typ(s.AllOf[0], hint)
	}
	switch basicType(s) {
	case "string":
		if s.Format == "binary" {
			return "[]byte"
		}
		return "string"
	case "integer":
		if s.Format == "int32" {
			return "int32"
		}
		return "int64"
	case "number":
		if s.Format == "float" {
			return "float32"
		}
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		if s.Items == nil {
			return "[]any"
		}
		return "[]" + g.typ(s.Items, hint+"Item")
	case "object":
		if len(g.collect(s).props) > 0 {
			name := g.reserve(hint)
			g.structType(name, s)
			return name
		}
		if ap := s.AdditionalProperties; ap != nil && !ap.False {
			return "map[string]" + g.typ(ap, hint+"Value")
		}
		return "map[string]any"
	}
	return "any"
}

func basicType(s *spec.Schema) string {
	var types []string
	for _, t := range s.Type {
		if t != "null" {
			types = append(types, t)
		}
	}
	switch {
	case len(types) == 1:
		return types[0]
	case len(types) > 1:
		return ""
	case len(s.Enum) > 0:
		switch s.Enum[0].(type) {
		case string:
			return "string"
		case bool:
			return "boolean"
		case float64:
			return "number"
		}
		return ""
	case len(s.Properties) > 0 || s.AdditionalProperties != nil || len(s.AllOf) > 0:
		return "object"
	case s.Items != nil:
		return "array"
	}
	return ""
}

type shape struct {
	props    map[string]*spec.Schema
	required map[string]bool
}

func (g *gen) collect(s *spec.Schema) shape {
	sh := shape{props: map[string]*spec.Schema{}, required: map[string]bool{}}
	g.merge(&sh, s, 0)
	return sh
}

func (g *gen) merge(sh *shape, s *spec.Schema, depth int) {
	if s == nil || depth > 32 {
		return
	}
	if s.Ref != "" {
		g.merge(sh, g.doc.Components.Schemas[spec.SchemaName(s.Ref)], depth+1)
		return
	}
	for k, p := range s.Properties {
		sh.props[k] = p
	}
	for _, r := range s.Required {
		sh.required[r] = true
	}
	for _, a := range s.AllOf {
		g.merge(sh, a, depth+1)
	}
}

// structType declares an object schema as a Go struct called name.
func (g *gen) structType(name string, s *spec.Schema) {
	sh := g.collect(s)
	used := map[string]bool{}
	var fields []field
	for _, pn := range spec.SortedKeys(sh.props) {
		p := sh.props[pn]
		fname := unique(exported(pn), used)
		optional := !sh.required[pn]
		fields = append(fields, field{
			name: fname,
			typ:  ptr(g.typ(p, name+fname), optional || nullable(p)),
			doc:  goDoc(p.Description, p.Deprecated),
			tag:  jsonTag(pn, optional),
		})
	}
	g.decls = append(g.decls, goDoc(s.Description, s.Deprecated)+structDecl(name, fields))
}

func structDecl(name string, fields []field) string {
	var b strings.Builder
	fmt.Fprintf(&b, "type %s struct {\n", name)
	for _, f := range fields {
		b.WriteString(f.doc)
		fmt.Fprintf(&b, "%s %s %s\n", f.name, f.typ, f.tag)
	}
	b.WriteString("}\n\n")
	return b.String()
}

func (g *gen) services(b *strings.Builder, n *node) {
	children := spec.SortedKeys(n.children)
	used := map[string]bool{}
	props := make([]string, len(children))
	for i, name := range children {
		props[i] = unique(exported(name), used)
	}
	names := make([]string, len(n.routes))
	for i, r := range n.routes {
		names[i] = unique(exported(r.Method), used)
	}

	if n.prefix == "" {
		b.WriteString("// Client is the entry point of the SDK.\n")
	} else {
		fmt.Fprintf(b, "// %s groups the %s operations.\n", n.class, n.prefix)
	}
	fmt.Fprintf(b, "type %s struct {\n\tbase *base\n", n.class)
	for i, name := range children {
		fmt.Fprintf(b, "\t%s *%s\n", props[i], n.children[name].class)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func new%s(b *base) *%s {\n\treturn &%s{\n\t\tbase: b,\n", n.class, n.class, n.class)
	for i, name := range children {
		fmt.Fprintf(b, "\t\t%s: new%s(b),\n", props[i], n.children[name].class)
	}
	b.WriteString("\t}\n}\n\n")

	for i, r := range n.routes {
		g.method(b, n, r, names[i])
	}
	for _, name := range children {
		g.services(b, n.children[name])
	}
}

func (g *gen) method(b *strings.Builder, n *node, r spec.Route, name string) {
	op := r.Op
	base := n.prefix + name
	used := map[string]bool{"Body": op.RequestBody != nil}
	var fields []field
	var calls []string
	bodyKind, contentType := "", ""

	for _, p := range op.Params {
		fname := unique(exported(p.Name), used)
		optional := !p.Required && p.In != "path"
		fields = append(fields, field{
			name: fname,
			typ:  ptr(g.typ(p.Schema, base+fname), optional || nullable(p.Schema)),
		})
		calls = append(calls, fmt.Sprintf("{in: %s, name: %s, style: %s, value: p.%s}",
			strconv.Quote(p.In), strconv.Quote(p.Name), strconv.Quote(p.SerStyle()), fname))
	}

	if rb := op.RequestBody; rb != nil {
		ct, mt := spec.PickMedia(rb.Content)
		var schema *spec.Schema
		if mt != nil {
			schema = mt.Schema
		}
		kind := spec.MediaKind(ct)
		var t string
		switch {
		case kind == "raw" && strings.HasPrefix(ct, "text/"):
			t = "string"
		case kind == "raw":
			t = "io.Reader"
			g.io = true
		default:
			t = g.typ(schema, base+"Body")
		}
		bodyKind, contentType = kind, ct
		fields = append(fields, field{name: "Body", typ: ptr(t, !rb.Required), doc: goDoc(rb.Description, false)})
	}
	resType, parse := g.response(op, base+"Response")

	paramsType := ""
	sig := "ctx context.Context"
	if len(fields) > 0 {
		paramsType = g.reserve(base + "Params")
		g.decls = append(g.decls, fmt.Sprintf("// %s holds the parameters of %s.\n", paramsType, name)+structDecl(paramsType, fields))
		sig += ", p " + paramsType
	}
	sig += ", opts ...RequestOption"
	ret := "error"
	if resType != "" {
		ret = "(" + resType + ", error)"
	}

	text := strings.TrimSpace(op.Summary + "\n\n" + op.Description)
	if text == "" {
		text = fmt.Sprintf("%s sends %s %s.", name, strings.ToUpper(op.Method), op.Path)
	}
	b.WriteString(goDoc(text, op.Deprecated))
	fmt.Fprintf(b, "func (s *%s) %s(%s) %s {\n", n.class, name, sig, ret)

	lines := []string{
		"method: " + strconv.Quote(strings.ToUpper(op.Method)),
		"path: " + strconv.Quote(op.Path),
	}
	if len(calls) > 0 {
		lines = append(lines, "params: []param{"+strings.Join(calls, ", ")+"}")
	}
	if bodyKind != "" {
		lines = append(lines, "body: p.Body", "bodyKind: "+strconv.Quote(bodyKind),
			"contentType: "+strconv.Quote(contentType))
	}
	lines = append(lines, "parse: "+strconv.Quote(parse))
	req := "request{\n" + strings.Join(lines, ",\n") + ",\n}"

	if resType == "" {
		fmt.Fprintf(b, "\treturn s.base.do(ctx, %s, nil, opts)\n", req)
	} else {
		fmt.Fprintf(b, "\tvar out %s\n\terr := s.base.do(ctx, %s, &out, opts)\n\treturn out, err\n", resType, req)
	}
	b.WriteString("}\n\n")
}

func (g *gen) response(op spec.Op, hint string) (string, string) {
	for _, code := range spec.SortedKeys(op.Responses) {
		if !strings.HasPrefix(code, "2") {
			continue
		}
		ct, mt := spec.PickMedia(op.Responses[code].Content)
		switch {
		case mt == nil || code == "204":
			return "", "void"
		case spec.MediaKind(ct) == "json":
			return g.typ(mt.Schema, hint), "json"
		case strings.HasPrefix(ct, "text/"):
			return "string", "text"
		default:
			return "[]byte", "blob"
		}
	}
	return "any", "json"
}

func goDoc(text string, deprecated bool) string {
	text = strings.TrimSpace(text)
	var b strings.Builder
	if text != "" {
		for line := range strings.SplitSeq(text, "\n") {
			b.WriteString(strings.TrimRight("// "+line, " "))
			b.WriteString("\n")
		}
	}
	if deprecated {
		if text != "" {
			b.WriteString("//\n")
		}
		b.WriteString("// Deprecated: true.\n")
	}
	return b.String()
}

func jsonTag(name string, optional bool) string {
	v := name
	if optional {
		v += ",omitempty"
	}
	if strings.Contains(v, "`") {
		return strconv.Quote(`json:"` + v + `"`)
	}
	return "`json:\"" + v + "\"`"
}

func nullable(s *spec.Schema) bool {
	return s != nil && (s.Nullable || slices.Contains(s.Type, "null"))
}

func ptr(t string, optional bool) string {
	if optional && !nilable(t) {
		return "*" + t
	}
	return t
}

func nilable(t string) bool {
	return t == "any" || t == "io.Reader" || strings.HasPrefix(t, "[]") || strings.HasPrefix(t, "map[")
}

func exported(s string) string {
	var b strings.Builder
	for _, w := range strings.FieldsFunc(s, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) }) {
		if v, ok := initialisms[strings.ToLower(w)]; ok {
			b.WriteString(v)
			continue
		}
		r := []rune(w)
		b.WriteString(strings.ToUpper(string(r[0])))
		b.WriteString(string(r[1:]))
	}
	out := b.String()
	if out == "" || unicode.IsDigit([]rune(out)[0]) {
		out = "X" + out
	}
	return out
}

func unique(name string, used map[string]bool) string {
	out := name
	for i := 2; used[out]; i++ {
		out = fmt.Sprintf("%s%d", name, i)
	}
	used[out] = true
	return out
}
